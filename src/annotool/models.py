"""SQLAlchemy tables (plan §4). Structured data only; export strings are
generated by serialize.py.

Deviation from §4: `annotation.flags_json` holds the import "needs attention"
flags (needed for the amber dots; raw_cell alone cannot represent them all).
"""
from __future__ import annotations

from datetime import datetime

from sqlalchemy import JSON, Boolean, DateTime, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def _now() -> datetime:
    return datetime.now()


class Base(DeclarativeBase):
    pass


class Batch(Base):
    __tablename__ = "batch"
    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String, unique=True)
    kind: Mapped[str] = mapped_column(String, default="annotate")  # annotate | review
    sheet_name: Mapped[str | None] = mapped_column(String)
    source_file: Mapped[str | None] = mapped_column(String)
    annotators_json: Mapped[list | None] = mapped_column(JSON)  # review batches: [id of A, id of B]
    created_at: Mapped[datetime] = mapped_column(DateTime, default=_now)
    sentences: Mapped[list["Sentence"]] = relationship(
        back_populates="batch", order_by="Sentence.position", cascade="all, delete-orphan"
    )


class Sentence(Base):
    __tablename__ = "sentence"
    __table_args__ = (UniqueConstraint("batch_id", "sent_id"),)
    id: Mapped[int] = mapped_column(primary_key=True)
    batch_id: Mapped[int] = mapped_column(ForeignKey("batch.id"), index=True)
    document_id: Mapped[str] = mapped_column(String, index=True)
    sent_id: Mapped[str] = mapped_column(String)
    position: Mapped[int] = mapped_column(Integer)
    text: Mapped[str] = mapped_column(Text)
    batch: Mapped[Batch] = relationship(back_populates="sentences")


class Annotator(Base):
    __tablename__ = "annotator"
    id: Mapped[int] = mapped_column(primary_key=True)
    code: Mapped[str] = mapped_column(String, unique=True)
    display_name: Mapped[str | None] = mapped_column(String)


class Annotation(Base):
    __tablename__ = "annotation"
    __table_args__ = (UniqueConstraint("sentence_id", "annotator_id"),)
    id: Mapped[int] = mapped_column(primary_key=True)
    sentence_id: Mapped[int] = mapped_column(ForeignKey("sentence.id"), index=True)
    annotator_id: Mapped[int] = mapped_column(ForeignKey("annotator.id"), index=True)
    status: Mapped[str] = mapped_column(String, default="todo")  # todo | none | done
    arousal: Mapped[int | None] = mapped_column(Integer)
    source: Mapped[str | None] = mapped_column(String)
    polarity_json: Mapped[list] = mapped_column(JSON, default=list)
    flags_json: Mapped[list] = mapped_column(JSON, default=list)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=_now)
    edited_at: Mapped[datetime | None] = mapped_column(DateTime)  # set by UI edits only; drives "Continue"
    sentence: Mapped[Sentence] = relationship()
    emotions: Mapped[list["Emotion"]] = relationship(
        back_populates="annotation", order_by="Emotion.ord", cascade="all, delete-orphan"
    )


class Emotion(Base):
    __tablename__ = "emotion"
    id: Mapped[int] = mapped_column(primary_key=True)
    annotation_id: Mapped[int] = mapped_column(ForeignKey("annotation.id"), index=True)
    ord: Mapped[int] = mapped_column(Integer)  # 0 = primary
    tag: Mapped[str] = mapped_column(String)
    annotation: Mapped[Annotation] = relationship(back_populates="emotions")
    spans: Mapped[list["Span"]] = relationship(
        back_populates="emotion", order_by="Span.id", cascade="all, delete-orphan"
    )


class Span(Base):
    __tablename__ = "span"
    id: Mapped[int] = mapped_column(primary_key=True)
    emotion_id: Mapped[int] = mapped_column(ForeignKey("emotion.id"), index=True)
    slot: Mapped[str] = mapped_column(String)  # cue | obj | act | exp
    ord: Mapped[int] = mapped_column(Integer)
    group_no: Mapped[int] = mapped_column(Integer, default=0)
    start_tok: Mapped[int] = mapped_column(Integer)
    end_tok: Mapped[int] = mapped_column(Integer)
    emotion: Mapped[Emotion] = relationship(back_populates="spans")


class ReviewDecision(Base):
    __tablename__ = "review_decision"
    id: Mapped[int] = mapped_column(primary_key=True)
    sentence_id: Mapped[int] = mapped_column(ForeignKey("sentence.id"), index=True)
    field: Mapped[str] = mapped_column(String)
    final_value: Mapped[str | None] = mapped_column(Text)
    resolved: Mapped[bool] = mapped_column(Boolean, default=False)
    note: Mapped[str | None] = mapped_column(Text)
    reviewer: Mapped[str | None] = mapped_column(String)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=_now)


class RawCell(Base):
    """Verbatim legacy cell text kept from imports (plan §5.3)."""
    __tablename__ = "raw_cell"
    annotation_id: Mapped[int] = mapped_column(ForeignKey("annotation.id"), primary_key=True)
    field: Mapped[str] = mapped_column(String, primary_key=True)
    text: Mapped[str] = mapped_column(Text)
